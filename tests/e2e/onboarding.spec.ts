import { randomUUID } from "node:crypto";
import { test, expect } from "@playwright/test";
import { encode } from "next-auth/jwt";
import { Pool } from "pg";

test.describe("authenticated onboarding", () => {
  test.setTimeout(90_000);
  test.skip(!process.env.E2E_DATABASE_URL, "Set E2E_DATABASE_URL to a migrated, seeded disposable database.");
  let db: Pool;
  const users: string[] = [];
  test.beforeAll(() => { db = new Pool({ connectionString: process.env.E2E_DATABASE_URL! }); });
  test.afterAll(async () => { if (db) { await db.query("DELETE FROM users WHERE id = ANY($1::uuid[])", [users]); await db.end(); } });

  test("onboards, reloads, respecs, changes timezone, and enforces admin access", async ({ page, context }, testInfo) => {
    const browserErrors: string[] = [];
    page.on("pageerror", (error) => browserErrors.push(error.message));
    page.on("console", (message) => { if (message.type() === "error") browserErrors.push(message.text()); });
    const user = { id: randomUUID(), player: { id: randomUUID() } };
    users.push(user.id);
    await db.query("INSERT INTO users (id, email, created_at, updated_at) VALUES ($1, $2, now(), now())", [user.id, `${user.id}@e2e.example.test`]);
    await db.query("INSERT INTO players (id, user_id, created_at, updated_at) VALUES ($1, $2, now(), now())", [user.player.id, user.id]);
    const jwt = await encode({ secret: process.env.AUTH_SECRET!, token: { sub: user.id }, maxAge: 3600 });
    await context.addCookies([{ name: "next-auth.session-token", value: jwt, domain: "127.0.0.1", path: "/", httpOnly: true, secure: false, sameSite: "Lax" }]);
    await page.goto("/home");
    await expect(page).toHaveURL(/\/onboarding$/);
    await page.getByRole("button", { name: "Continue", exact: true }).click();
    await page.getByLabel("Your timezone").fill("America/Denver");
    await page.getByRole("button", { name: "Continue", exact: true }).click();
    await page.getByRole("button", { name: "Decrease Fitness Focus" }).click();
    await page.getByRole("button", { name: "Increase Hobbies Focus" }).click();
    await expect(page.getByText(/0 points remaining/)).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("focus-allocator.png"), fullPage: true, caret: "initial" });
    await page.getByRole("button", { name: "Continue", exact: true }).click();
    await page.getByRole("button", { name: "Complete onboarding" }).click();
    await expect(page).toHaveURL(/\/home$/);
    await page.reload();
    await expect(page.getByRole("heading", { name: "You're all set." })).toBeVisible();
    await page.goto("/onboarding");
    await expect(page).toHaveURL(/\/home$/);
    const me = await (await context.request.get("/api/me")).json();
    expect(me.player.id).toBe(user.player!.id);
    expect(me.player.focus).toHaveLength(8);
    await page.goto("/settings");
    await expect(page.getByLabel("Fitness points")).toHaveText("5");
    await page.getByRole("button", { name: "Decrease Hobbies Focus" }).click();
    await page.getByRole("button", { name: "Increase Fitness Focus" }).click();
    await page.getByRole("button", { name: "Save Focus", exact: true }).click();
    await expect(page.getByText("Focus saved.", { exact: true })).toBeVisible();
    await page.getByLabel("Your timezone").fill("Europe/London");
    await page.getByRole("button", { name: "Save timezone", exact: true }).click();
    await expect(page.getByText("Timezone saved.", { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByLabel("Your timezone")).toHaveValue("Europe/London");
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath("settings.png"), fullPage: true, caret: "initial" });
    expect((await context.request.get("/api/admin")).status()).toBe(403);
    await page.goto("/admin"); await expect(page).toHaveURL(/\/not-authorized$/);
    await db.query("UPDATE users SET role = 'ADMIN', updated_at = now() WHERE id = $1", [user.id]);
    expect((await context.request.get("/api/admin")).status()).toBe(200);
    await page.goto("/admin"); await expect(page.getByRole("heading", { name: "Administrator access" })).toBeVisible();
    expect((await db.query("SELECT count(*)::int FROM player_quest_slots WHERE player_id = $1", [user.player.id])).rows[0].count).toBe(0);
    expect((await db.query("SELECT count(*)::int FROM player_skill_focus_history WHERE player_id = $1", [user.player.id])).rows[0].count).toBe(10);
    await page.getByRole("button", { name: "Sign out", exact: true }).click();
    await expect(page).toHaveURL("/");
    expect((await context.request.get("/api/me")).status()).toBe(401);
    await page.goto("/home"); await expect(page).toHaveURL(/\/login$/);
    expect(browserErrors).toEqual([]);
  });
});
